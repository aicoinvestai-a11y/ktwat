/**
 * تجهيز النص المنطوق — خطوتي 🎧
 *
 * بعض العبارات مكتوبة في المحتوى برموز مختصرة تُقرأ خطأً أو تُتخطّى في محرّكات النطق.
 * ومحرّك الجهاز لا ينطق الرموز إطلاقاً، فيسمع الطفل «من جد النبي؟» بلا صلاة كاملة — وهذا خطأ شرعي.
 *
 * القاعدة المطبَّقة هنا: كل رمز ﷺ يُنطق كاملاً «صلى الله عليه وسلم».
 *
 * ملاحظة مهمة: معرّفات الملفات المسجّلة تُحسب من **النص المكتوب** كما هو (انظر voice-manifest.ts)،
 * والتوسيع يُطبَّق على **النص المنطوق** فقط. فالتسجيل البشري أو المولَّد ينطق الصلاة كاملة،
 * بينما يحتفظ الموقع بالمكتوب المختصر.
 */

/** الرموز المختصرة → النطق الكامل (مقارنة نصية حتمية بلا regex — تجنّباً لحالة lastIndex) */
const HONORIFICS: { symbol: string; spoken: string }[] = [
  { symbol: '\uFDFA', spoken: 'صلى الله عليه وسلم' },
  { symbol: '\uFDFB', spoken: 'جلَّ جلاله' },
];

/** الأرقام → كلمات (الأرقام المفردة تُقرأ خطأً أو بلغة أخرى في بعض المحرّكات) */
const DIGITS: Record<string, string> = {
  '٠': 'صفر', '١': 'واحد', '٢': 'اثنان', '٣': 'ثلاثة', '٤': 'أربعة',
  '٥': 'خمسة', '٦': 'ستة', '٧': 'سبعة', '٨': 'ثمانية', '٩': 'تسعة',
  '0': 'صفر', '1': 'واحد', '2': 'اثنان', '3': 'ثلاثة', '4': 'أربعة',
  '5': 'خمسة', '6': 'ستة', '7': 'سبعة', '8': 'ثمانية', '9': 'تسعة',
};

/** النص كما يجب أن يُنطق (لا كما يُكتب) */
export function speechText(text: string): string {
  let out = text;
  for (const h of HONORIFICS) out = out.split(h.symbol).join(h.spoken);
  out = out.replace(/[٠-٩0-9]/g, (d) => ` ${DIGITS[d] ?? d} `);
  return out.replace(/\s+/g, ' ').trim();
}

/** هل يحتاج النص توسيعاً عند النطق؟ (يستخدمه المولّد لتنبيه من يسجّل بصوته) */
export function needsSpokenExpansion(text: string): boolean {
  return HONORIFICS.some((h) => text.includes(h.symbol)) || /[٠-٩0-9]/.test(text);
}
